/**
 * Robust CSV Line Parser handling quotes with commas
 */
export function parseCSVToCompanies(csvString: string): Company[] {
  const lines = csvString.trim().split(/\r?\n/);
  if (lines.length < 2) return [];

  const companies: Company[] = [];

  // Parse lines ignoring header if present
  for (let i = 1; i < lines.length; i++) {
    const rawLine = lines[i].trim();
    if (!rawLine) continue;

    // Parse comma-separated line handling quotation marks
    const row: string[] = [];
    let insideQuote = false;
    let currentCell = '';

    for (let charIndex = 0; charIndex < rawLine.length; charIndex++) {
      const char = rawLine[charIndex];

      if (char === '"') {
        insideQuote = !insideQuote;
      } else if (char === ',' && !insideQuote) {
        row.push(currentCell.trim());
        currentCell = '';
      } else {
        currentCell += char;
      }
    }
    row.push(currentCell.trim());

    const sehir = (row[0] || '').replace(/^"|"$/g, '').trim();
    const ilce = (row[1] || '').replace(/^"|"$/g, '').trim();
    const tabelaUnvani = (row[2] || '').replace(/^"|"$/g, '').trim();
    const musteriUnvani = (row[3] || '').replace(/^"|"$/g, '').trim();
    const adres = (row[4] || '').replace(/^"|"$/g, '').trim();
    const iletisim1 = (row[5] || '').replace(/^"|"$/g, '').trim();
    const iletisim2 = (row[6] || '').replace(/^"|"$/g, '').trim();

    // At least one identifier must exist
    if (sehir || tabelaUnvani || musteriUnvani || adres) {
      companies.push({
        id: `comp-${i}-${Math.random().toString(36).substring(2, 7)}`,
        sehir,
        ilce,
        tabelaUnvani,
        musteriUnvani,
        adres,
        iletisim1,
        iletisim2,
      });
    }
  }

  return companies;
}

